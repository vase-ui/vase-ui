import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it, onTestFinished } from 'vitest';
import { TEMPORAL_REFERENCE, writeBarrel } from '../scripts/build.ts';

const HEADER = '// Generated by scripts/build.ts. Do not edit.\n';

function writeBarrelOf(entries: Record<string, string | undefined>): string {
  const root = mkdtempSync(join(tmpdir(), 'write-barrel-'));
  onTestFinished(() => {
    rmSync(root, { recursive: true, force: true });
  });
  for (const [name, indexText] of Object.entries(entries)) {
    mkdirSync(join(root, name));
    if (indexText !== undefined) {
      writeFileSync(join(root, name, 'index.ts'), indexText);
    }
  }
  const barrel = join(root, 'index.ts');
  writeBarrel(barrel, [root]);
  return readFileSync(barrel, 'utf8');
}

describe('writeBarrel', () => {
  it('exports each entry that has an index.ts, in order', () => {
    expect(
      writeBarrelOf({
        tabs: 'export {};',
        button: 'export {};',
        common: 'export {};',
        empty: undefined,
      }),
    ).toBe(`${HEADER}export * from './button';\nexport * from './tabs';\n`);
  });

  it('leaves out an entry whose index.ts starts with the Temporal reference line', () => {
    expect(
      writeBarrelOf({
        button: 'export {};',
        calendar: `${TEMPORAL_REFERENCE}\nexport {};`,
      }),
    ).toBe(`${HEADER}export * from './button';\n`);
  });

  it('keeps an entry that has another first line or has the reference line later', () => {
    expect(
      writeBarrelOf({
        dom: '/// <reference lib="dom" />\nexport {};',
        later: `export {};\n${TEMPORAL_REFERENCE}`,
      }),
    ).toBe(`${HEADER}export * from './dom';\nexport * from './later';\n`);
  });

  it('exports nothing when no entry is left', () => {
    expect(writeBarrelOf({ calendar: `${TEMPORAL_REFERENCE}\nexport {};` })).toBe(
      `${HEADER}export {};\n`,
    );
  });
});
