import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import type { UserConfig } from 'tsdown';
import Vue from 'unplugin-vue/rolldown';

const NOT_ENTRY_FOLDERS = new Set(['internals', 'utils', 'common']);

function entryNames(sourceRoot: string): string[] {
  if (!existsSync(sourceRoot)) {
    return [];
  }
  return readdirSync(sourceRoot, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() &&
        !NOT_ENTRY_FOLDERS.has(entry.name) &&
        existsSync(join(sourceRoot, entry.name, 'index.ts')),
    )
    .map((entry) => entry.name);
}

export function familyEntries(sourceRoot: string): Record<string, string> {
  return Object.fromEntries(
    entryNames(sourceRoot).map((name) => [`${name}/index`, join(sourceRoot, name, 'index.ts')]),
  );
}

export function writeBarrel(barrelFile: string, sourceRoots: string[]): void {
  const specifiers = sourceRoots
    .flatMap((sourceRoot) =>
      entryNames(sourceRoot)
        .filter((name) => !name.startsWith('unstable-'))
        .map((name) => relative(dirname(barrelFile), join(sourceRoot, name))),
    )
    .map((path) => (path.startsWith('.') ? path : `./${path}`))
    .sort();
  const lines = specifiers.length
    ? specifiers.map((specifier) => `export * from '${specifier}';`)
    : ['export {};'];
  mkdirSync(dirname(barrelFile), { recursive: true });
  writeFileSync(
    barrelFile,
    `// Generated by scripts/build.ts. Do not edit.\n${lines.join('\n')}\n`,
  );
}

export function buildOptions(entry: Record<string, string>, outDir: string): UserConfig {
  return {
    entry,
    outDir,
    format: 'esm',
    platform: 'neutral',
    target: 'baseline-widely-available',
    plugins: [Vue({ isProduction: true })],
    dts: { generator: 'tsc', tsc: { vue: true } },
    deps: { onlyBundle: [] },
  };
}
