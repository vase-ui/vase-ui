/**
 * Indicates the unit that the face shows.
 * @type {'hour' | 'minute' | 'second'}
 */
export const view = 'data-view';
/**
 * Present when the clock is disabled.
 */
export const disabled = 'data-disabled';
/**
 * Present when the user can see the time but not change it.
 */
export const readonly = 'data-readonly';
/**
 * Present while the user is dragging on the face.
 */
export const dragging = 'data-dragging';
/**
 * Present when the clock has no value.
 */
export const empty = 'data-empty';
/**
 * Present when the hand points at the inner ring of a 24-hour face.
 */
export const inner = 'data-inner';
/**
 * Present when the hand points between two numbers of the face.
 */
export const betweenNumbers = 'data-between-numbers';
