/**
 * Present when the field is disabled.
 */
export const disabled = 'data-disabled';
/**
 * Present when the user cannot change the value of the field.
 */
export const readonly = 'data-readonly';
/**
 * Present when the user must enter a value before a form submits.
 */
export const required = 'data-required';
/**
 * Present when no segment has a number.
 */
export const empty = 'data-empty';
/**
 * Present when each segment has a number, so that the field has a value.
 */
export const complete = 'data-complete';
/**
 * Present when the field is valid (when wrapped in Field.Root).
 */
export const valid = 'data-valid';
/**
 * Present when the field is invalid (when wrapped in Field.Root).
 */
export const invalid = 'data-invalid';
/**
 * Present when the field has been touched (when wrapped in Field.Root).
 */
export const touched = 'data-touched';
/**
 * Present when the value of the field has changed (when wrapped in Field.Root).
 */
export const dirty = 'data-dirty';
/**
 * Present when the field has a value.
 */
export const filled = 'data-filled';
